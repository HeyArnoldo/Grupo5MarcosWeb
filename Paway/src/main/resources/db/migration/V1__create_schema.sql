-- Paway schema. Flyway owns it; Hibernate only validates it (ddl-auto=validate).
-- CHECK constraints mirror the Bean Validation rules on the JPA entities, so the
-- database stays consistent even if a row is written outside the application.

create table customer (
    id          bigint generated by default as identity,
    full_name   varchar(100) not null,
    document    varchar(8)   not null,
    email       varchar(150) not null,
    phone       varchar(25)  not null,
    created_at  timestamp with time zone not null default now(),
    constraint pk_customer primary key (id),
    constraint uk_customer_document unique (document),
    constraint uk_customer_email unique (email),
    constraint ck_customer_full_name check (length(btrim(full_name)) > 0),
    constraint ck_customer_document check (document ~ '^[0-9]{8}$'),
    constraint ck_customer_phone check (phone ~ '^[+0-9 ()-]{7,25}$')
);

-- Origin agencies (reference data, not demo data).
create table agency (
    id        bigint generated by default as identity,
    name      varchar(60) not null,
    district  varchar(60) not null,
    constraint pk_agency primary key (id),
    constraint uk_agency_name unique (name)
