-- The application reads nextval() first so the guide (PW-<year>-<id>) is known
-- before the INSERT; the column default keeps manual inserts working too.
create sequence shipment_id_seq;

create table shipment (
    id                  bigint        not null default nextval('shipment_id_seq'),
    guide               varchar(20)   not null,
    customer_id         bigint        not null,
    origin_agency_id    bigint        not null,
    recipient           varchar(100)  not null,
    recipient_document  varchar(8)    not null,
    province            varchar(20)   not null,
    district            varchar(60)   not null,
    category            varchar(20)   not null,
    weight_kg           numeric(6, 2) not null,
    quantity            integer       not null,
    total               numeric(10, 2) not null,
    status              varchar(20)   not null,
    observation         varchar(500)  not null default '',
    created_at          timestamp with time zone not null,
    updated_at          timestamp with time zone not null,
    version             bigint        not null default 0,
    constraint pk_shipment primary key (id),
    constraint uk_shipment_guide unique (guide),
    constraint fk_shipment_customer foreign key (customer_id) references customer (id),
    constraint fk_shipment_origin_agency foreign key (origin_agency_id) references agency (id),
    constraint ck_shipment_guide check (guide ~ '^PW-[0-9]{4}-[0-9]{4,}$'),
    constraint ck_shipment_recipient check (length(btrim(recipient)) > 0),
    constraint ck_shipment_recipient_document check (recipient_document ~ '^[0-9]{8}$'),
    constraint ck_shipment_province check (province in ('lima', 'huarochiri', 'huaral', 'canete')),
    constraint ck_shipment_category check (category in ('textil', 'otros', 'hogar_higiene', 'tecnologia', 'joyeria')),
    constraint ck_shipment_weight check (weight_kg > 0 and weight_kg <= 1000),
    constraint ck_shipment_quantity check (quantity between 1 and 100),
    constraint ck_shipment_total check (total >= 0),
    constraint ck_shipment_status check (status in
        ('REGISTERED', 'WAREHOUSE', 'TRANSIT', 'DELIVERY', 'DELIVERED', 'INCIDENT', 'CANCELLED'))
);

alter sequence shipment_id_seq owned by shipment.id;

create index ix_shipment_customer on shipment (customer_id);
create index ix_shipment_origin_agency on shipment (origin_agency_id);
create index ix_shipment_status on shipment (status);

-- Tracking timeline: one row per status change, never updated or deleted by the app.
create table shipment_event (
    id           bigint generated by default as identity,
    shipment_id  bigint       not null,
    status       varchar(20)  not null,
    occurred_at  timestamp with time zone not null,
    observation  varchar(500) not null default '',
    constraint pk_shipment_event primary key (id),
    constraint fk_shipment_event_shipment foreign key (shipment_id) references shipment (id) on delete cascade,
    constraint ck_shipment_event_status check (status in
        ('REGISTERED', 'WAREHOUSE', 'TRANSIT', 'DELIVERY', 'DELIVERED', 'INCIDENT', 'CANCELLED'))
);

create index ix_shipment_event_timeline on shipment_event (shipment_id, occurred_at, id);

-- Libro de Reclamaciones: one sheet per submission token (idempotent form submit).
create sequence complaint_number_seq;

create table complaint (
    id                 bigint generated by default as identity,
    token              uuid          not null,
    sheet_number       varchar(20)   not null,
    created_at         timestamp with time zone not null,
    consumer_name      varchar(150)  not null,
    consumer_document  varchar(20)   not null,
    address            varchar(250)  not null,
    email              varchar(150)  not null,
    phone              varchar(25)   not null,
    minor              boolean       not null default false,
    guardian_name      varchar(150)  not null default '',
    guardian_document  varchar(20)   not null default '',
    guardian_contact   varchar(250)  not null default '',
    complaint_type     varchar(10)   not null,
    item_type          varchar(10)   not null,
    amount             numeric(10, 2),
    guide              varchar(40)   not null default '',
    description        varchar(1000) not null,
    detail             varchar(4000) not null,
    consumer_request   varchar(2000) not null,
    response_channel   varchar(10)   not null,
    response           varchar(4000),
    response_delivery  varchar(500),
    responded_at       timestamp with time zone,
    constraint pk_complaint primary key (id),
    constraint uk_complaint_token unique (token),
    constraint uk_complaint_sheet_number unique (sheet_number),
    constraint ck_complaint_sheet_number check (sheet_number ~ '^PW-WEB-[0-9]{6,}$'),
    constraint ck_complaint_document check (consumer_document ~ '^[A-Za-z0-9-]{6,20}$'),
    constraint ck_complaint_type check (complaint_type in ('RECLAMO', 'QUEJA')),
    constraint ck_complaint_item_type check (item_type in ('SERVICIO', 'PRODUCTO')),
    constraint ck_complaint_response_channel check (response_channel in ('EMAIL', 'DOMICILIO')),
    constraint ck_complaint_amount check (amount is null or amount >= 0),
    constraint ck_complaint_guardian check (not minor or (length(btrim(guardian_name)) > 0
        and guardian_document ~ '^[A-Za-z0-9-]{6,20}$' and length(btrim(guardian_contact)) > 0)),
    constraint ck_complaint_response check ((response is null) = (responded_at is null)
        and (response is null) = (response_delivery is null))
);

create index ix_complaint_created_at on complaint (created_at);
