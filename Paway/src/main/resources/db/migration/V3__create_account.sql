-- Login accounts. A CLIENT account owns exactly one customer (sender) row; the ADMIN
-- account has no customer. Demo customers from V2 have no account, so nobody can sign
-- in as them; their shipments stay trackable by guide.
create table account (
    id             bigint generated by default as identity,
    customer_id    bigint,
    email          varchar(150) not null,
    password_hash  varchar(100) not null,
    role           varchar(10)  not null,
    created_at     timestamp with time zone not null default now(),
    constraint pk_account primary key (id),
    constraint uk_account_customer unique (customer_id),
    constraint fk_account_customer foreign key (customer_id) references customer (id),
    constraint ck_account_role check (role in ('CLIENT', 'ADMIN')),
    constraint ck_account_role_customer check (
        (role = 'CLIENT' and customer_id is not null) or (role = 'ADMIN' and customer_id is null)),
    constraint ck_account_email check (length(btrim(email)) > 0)
);

create unique index ux_account_email_lower on account (lower(email));
